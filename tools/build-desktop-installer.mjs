/**
 * 桌面安装器（M22，ADR-040）——把**便携目录**变成"可安装"的一份东西。
 *
 * 为什么不用 electron-builder：它的 NSIS / winCodeSign 走 GitHub，本机拉不下来（M13c 实测）。
 * 所以这里只用 **Windows 自带**的东西：
 *   - `install.cmd` / `uninstall.cmd`：robocopy 复制 + 写快捷方式（PowerShell COM，无额外依赖）；
 *   - `--iexpress`：调用系统自带 `iexpress.exe` 把整个应用 + install.cmd 打成**单个 Setup.exe**
 *     （SED 里逐个列文件；IExpress 不支持目录递归）。
 *
 * 红线说明（写进 ADR）：安装目标**绝不允许 C 盘**；唯一例外是桌面 / 开始菜单的 `.lnk`
 * （Windows 上快捷方式只能放那儿），应用数据 / 缓存 / 日志仍全部落在安装盘。
 *
 * 用法：
 *   node tools/build-desktop-installer.mjs                 # 生成 install.cmd + uninstall.cmd
 *   node tools/build-desktop-installer.mjs --iexpress      # 另外尝试打单文件 Setup.exe
 */
import { spawnSync } from "node:child_process";
import { existsSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const repoRoot = resolve(import.meta.dirname, "..");
const portableRoot = resolve(repoRoot, "..", "dist-desktop", "chenxi-desktop");
const exeName = "chenxi-desktop.exe";
const wantIexpress = process.argv.includes("--iexpress");

if (!existsSync(join(portableRoot, exeName))) {
	process.stderr.write(
		`缺少便携目录：${portableRoot}\n请先运行：node "C:\\dev\\node-v22.23.2-win-x64\\node_modules\\npm\\bin\\npm-cli.js" run desktop-portable\n`,
	);
	process.exit(1);
}

/**
 * 安装脚本（ASCII-only：cmd.exe 按控制台代码页解析 .cmd，中文会乱）。
 * 用环境变量而不是命令行参数：cmd 里解析参数更容易出错，而这两项只给自动化用。
 *   CHENXI_INSTALL_DIR   目标目录（缺省 D:\Chenxi；以 C: 开头一律拒绝）
 *   CHENXI_NO_SHORTCUTS  设为 1 时不创建桌面 / 开始菜单快捷方式
 */
const installCmd = `@echo off
setlocal EnableExtensions
rem Chenxi desktop installer (generated by tools/build-desktop-installer.mjs)
rem Default target is D:\\Chenxi. Installing onto C: is refused (project rule).
set "SRC=%~dp0"
if "%CHENXI_INSTALL_DIR%"=="" (set "TARGET=D:\\Chenxi") else (set "TARGET=%CHENXI_INSTALL_DIR%")
if /i "%TARGET:~0,2%"=="C:" (
  echo chenxi-install: refusing to install onto the C drive: %TARGET%
  echo use CHENXI_INSTALL_DIR=D:\\somewhere to pick another location
  exit /b 2
)
echo chenxi-install: %SRC%  -^>  %TARGET%
if not exist "%TARGET%" mkdir "%TARGET%"
robocopy "%SRC%." "%TARGET%" /E /NFL /NDL /NJH /NJS /NP /XF install.cmd uninstall.cmd >nul
if errorlevel 8 (
  echo chenxi-install: copy failed ^(robocopy exit %ERRORLEVEL%^)
  exit /b 3
)
copy /y "%~dp0uninstall.cmd" "%TARGET%\\uninstall.cmd" >nul
if "%CHENXI_NO_SHORTCUTS%"=="1" goto done
powershell -NoProfile -ExecutionPolicy Bypass -Command ^
  "$ws = New-Object -ComObject WScript.Shell; $dirs = @([Environment]::GetFolderPath('Desktop'), (Join-Path $env:APPDATA 'Microsoft\\Windows\\Start Menu\\Programs')); foreach ($d in $dirs) { if (Test-Path $d) { $lnk = $ws.CreateShortcut((Join-Path $d 'Chenxi.lnk')); $lnk.TargetPath = '%TARGET%\\${exeName}'; $lnk.WorkingDirectory = '%TARGET%'; $lnk.Description = 'Chenxi local agent harness'; $lnk.Save() } }"
:done
echo chenxi-install: done -^> %TARGET%\\${exeName}
echo to uninstall: run %TARGET%\\uninstall.cmd
exit /b 0
`;

const uninstallCmd = `@echo off
setlocal EnableExtensions
rem Chenxi desktop uninstaller (generated). Removes shortcuts and the install folder.
set "TARGET=%~dp0"
for %%I in ("%TARGET%.") do set "TARGET=%%~fI"
if /i "%TARGET:~0,2%"=="C:" (
  echo chenxi-uninstall: refusing to touch the C drive: %TARGET%
  exit /b 2
)
powershell -NoProfile -ExecutionPolicy Bypass -Command ^
  "$ws = New-Object -ComObject WScript.Shell; $dirs = @([Environment]::GetFolderPath('Desktop'), (Join-Path $env:APPDATA 'Microsoft\\Windows\\Start Menu\\Programs')); foreach ($d in $dirs) { $p = Join-Path $d 'Chenxi.lnk'; if (Test-Path $p) { Remove-Item $p -Force } }"
echo chenxi-uninstall: removing %TARGET% ...
rem 脚本自身就在目标目录里：用**分离进程 + 延迟**删除，否则 rmdir 会因占用失败
start "" powershell -NoProfile -WindowStyle Hidden -Command "Start-Sleep -Seconds 2; Remove-Item -LiteralPath '%TARGET%' -Recurse -Force -ErrorAction SilentlyContinue"
exit /b 0
`;

writeFileSync(join(portableRoot, "install.cmd"), installCmd.replace(/\r?\n/g, "\r\n"), "ascii");
writeFileSync(join(portableRoot, "uninstall.cmd"), uninstallCmd.replace(/\r?\n/g, "\r\n"), "ascii");
process.stdout.write(`installer scripts ok: ${portableRoot}\\install.cmd (+ uninstall.cmd)\n`);

if (!wantIexpress) process.exit(0);

// ---- 单文件 Setup.exe（IExpress；逐个列文件，不支持目录递归） ----
const files = [];
const walk = (dir) => {
	for (const entry of readdirSync(dir, { withFileTypes: true })) {
		const full = join(dir, entry.name);
		if (entry.isDirectory()) walk(full);
		else if (entry.isFile()) files.push(full);
	}
};
walk(portableRoot);
files.push(join(portableRoot, "install.cmd"), join(portableRoot, "uninstall.cmd"));
const unique = [...new Set(files)];
if (unique.length > 400) {
	process.stderr.write(`iexpress: too many files (${unique.length}); aborting\n`);
	process.exit(1);
}

const sedPath = join(repoRoot, "..", ".dev", "tmp", "chenxi-iexpress.sed");
const setupPath = join(resolve(portableRoot, ".."), "Chenxi-Setup.exe");
const entries = unique.map((_, index) => `%FILE${index}%=`).join("\r\n");
const strings = unique
	.map((file, index) => {
		const rel = file.slice(portableRoot.length + 1);
		return `FILE${index}="${rel}"`;
	})
	.join("\r\n");
const sed = `[Version]
Class=IEXPRESS
SEDVersion=3
[Options]
PackagePurpose=InstallApp
ShowInstallProgramWindow=1
HideExtractAnimation=1
UseLongFileName=1
InsideCompressed=0
CAB_FixedSize=0
CAB_ResvCodeSigning=0
RebootMode=N
InstallPrompt=
DisplayLicense=
FinishMessage=
TargetName=${setupPath}
FriendlyName=Chenxi Setup
AppLaunched=install.cmd
PostInstallCmd=<None>
AdminQuietInstCmd=
UserQuietInstCmd=
SourceFiles=SourceFiles
[Strings]
${strings}
[SourceFiles]
SourceFiles0=${portableRoot}\\
[SourceFiles0]
${entries}
`;
writeFileSync(sedPath, sed.replace(/\r?\n/g, "\r\n"), "utf8");
process.stdout.write(`iexpress sed: ${sedPath} (${unique.length} files)\n`);
if (existsSync(setupPath)) rmSync(setupPath, { force: true });

const result = spawnSync(`${process.env.SystemRoot}\\System32\\iexpress.exe`, ["/N", "/Q", sedPath], {
	encoding: "utf8",
	windowsHide: true,
	timeout: 9 * 60 * 1000,
});
process.stdout.write(`iexpress exit=${result.status}\n`);
if (result.status === 0 && existsSync(setupPath)) {
	const bytes = statSync(setupPath).size;
	process.stdout.write(`setup ok: ${setupPath} (${bytes} bytes)\n`);
} else {
	process.stderr.write(`iexpress failed; install.cmd / uninstall.cmd are still available\n`);
	process.exitCode = 1;
}
